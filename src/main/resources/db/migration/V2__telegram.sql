-- V2 - Integração com o Telegram (perfil DOCENTE)
-- =====================================================================

-- Vínculo entre um docente e um chat do Telegram
CREATE TABLE telegram_vinculo (
                                  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  usuario_id       INTEGER      NOT NULL,
                                  chat_id          BIGINT       NOT NULL,
                                  telegram_user_id BIGINT,
                                  username         VARCHAR(64),
                                  nome_exibicao    VARCHAR(200),
                                  status           VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
                                  motivo_revogacao VARCHAR(30),
                                  expira_em        TIMESTAMP,                      -- validade do pedido pendente
                                  criado_em        TIMESTAMP    NOT NULL DEFAULT now(),
                                  confirmado_em    TIMESTAMP,
                                  atualizado_em    TIMESTAMP    NOT NULL DEFAULT now(),
                                  CONSTRAINT fk_tgv_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
                                  CONSTRAINT ck_tgv_status  CHECK (status IN ('PENDENTE', 'ATIVO', 'REVOGADO'))
);

-- Um vínculo vigente por docente e um docente por chat (revogados não contam)
CREATE UNIQUE INDEX ux_tgv_usuario_vigente ON telegram_vinculo(usuario_id)
    WHERE status IN ('PENDENTE', 'ATIVO');
CREATE UNIQUE INDEX ux_tgv_chat_vigente ON telegram_vinculo(chat_id)
    WHERE status IN ('PENDENTE', 'ATIVO');

-- Códigos de vínculo (só o hash SHA-256; o código em si nunca é guardado)
CREATE TABLE telegram_codigo_vinculo (
                                         id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         usuario_id  INTEGER     NOT NULL,
                                         codigo_hash VARCHAR(64) NOT NULL UNIQUE,
                                         expira_em   TIMESTAMP   NOT NULL,
                                         usado_em    TIMESTAMP,
                                         criado_em   TIMESTAMP   NOT NULL DEFAULT now(),
                                         CONSTRAINT fk_tgc_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE INDEX ix_tgc_usuario ON telegram_codigo_vinculo(usuario_id);

-- Mensagens do bot ligadas a um chamado (permite descobrir o chamado de uma resposta)
CREATE TABLE telegram_mensagem (
                                   id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   chat_id    BIGINT      NOT NULL,
                                   message_id BIGINT      NOT NULL,
                                   chamado_id BIGINT,
                                   direcao    VARCHAR(10) NOT NULL,                 -- ENVIADA ou RECEBIDA
                                   tipo       VARCHAR(30) NOT NULL,                 -- NOTIFICACAO, DETALHE, PEDIDO_RESPOSTA, RESPOSTA...
                                   criado_em  TIMESTAMP   NOT NULL DEFAULT now(),
                                   CONSTRAINT fk_tgm_chamado FOREIGN KEY (chamado_id) REFERENCES chamado(id),
                                   CONSTRAINT ck_tgm_direcao CHECK (direcao IN ('ENVIADA', 'RECEBIDA')),
                                   CONSTRAINT ux_tgm_chat_msg UNIQUE (chat_id, message_id)
);

CREATE INDEX ix_tgm_chamado ON telegram_mensagem(chamado_id);

-- Eventos do Telegram já tratados (o Telegram pode reenviar o mesmo evento)
CREATE TABLE telegram_update_processado (
                                            update_id     BIGINT    PRIMARY KEY,
                                            processado_em TIMESTAMP NOT NULL DEFAULT now()
);

-- Fila de notificações (outbox)
CREATE TABLE notificacao (
                             id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             usuario_id    INTEGER     NOT NULL,
                             chamado_id    BIGINT      NOT NULL,
                             canal         VARCHAR(20) NOT NULL DEFAULT 'TELEGRAM',
                             tipo          VARCHAR(30) NOT NULL,              -- ATRIBUICAO, NOVA_MENSAGEM
                             texto         TEXT        NOT NULL,
                             status        VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
                             tentativas    INTEGER     NOT NULL DEFAULT 0,
                             proximo_envio TIMESTAMP   NOT NULL DEFAULT now(),
                             erro          VARCHAR(500),
                             criado_em     TIMESTAMP   NOT NULL DEFAULT now(),
                             enviado_em    TIMESTAMP,
                             CONSTRAINT fk_not_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
                             CONSTRAINT fk_not_chamado FOREIGN KEY (chamado_id) REFERENCES chamado(id),
                             CONSTRAINT ck_not_status  CHECK (status IN ('PENDENTE', 'ENVIADA', 'FALHA', 'SEM_VINCULO'))
);

CREATE INDEX ix_not_fila    ON notificacao(status, proximo_envio);
CREATE INDEX ix_not_chamado ON notificacao(chamado_id);