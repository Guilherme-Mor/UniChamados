-- =====================================================================

-- Tentativas de vínculo com código inválido (por chat)
CREATE TABLE telegram_tentativa_invalida (
                                             id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             chat_id       BIGINT      NOT NULL,
                                             username      VARCHAR(64),
                                             nome_exibicao VARCHAR(200),
                                             criado_em     TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE INDEX ix_tgt_chat ON telegram_tentativa_invalida(chat_id, criado_em);

-- Liberações feitas pelo admin (auditoria e ponto de reinício do limite de códigos)
CREATE TABLE telegram_liberacao (
                                    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    tipo       VARCHAR(10) NOT NULL,                -- DOCENTE ou CHAT
                                    usuario_id INTEGER,                             -- docente liberado (tipo DOCENTE)
                                    chat_id    BIGINT,                              -- chat liberado (tipo CHAT)
                                    admin_id   INTEGER     NOT NULL,
                                    criado_em  TIMESTAMP   NOT NULL DEFAULT now(),
                                    CONSTRAINT fk_tgl_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
                                    CONSTRAINT fk_tgl_admin   FOREIGN KEY (admin_id)   REFERENCES usuario(id),
                                    CONSTRAINT ck_tgl_tipo    CHECK (tipo IN ('DOCENTE', 'CHAT'))
);

CREATE INDEX ix_tgl_usuario ON telegram_liberacao(usuario_id, criado_em);